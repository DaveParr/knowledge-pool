F = lambda name, body, tok=None: call("/function/" + name, body, tok)

def scenario(tag, creator, levels):
    print(f"\n\n################ SCENARIO {tag}: created by {creator}, levels {levels}\n")
    body = {"tag": tag, "cat_level": levels[0], "card_level": levels[1], "fmt_level": levels[2]}
    seed = show("seed", F("seed_as_guest", body) if creator == "guest" else F("seed_as_user", body, a))
    card, cat, fmt = seed["card"], seed["cat"], seed["fmt"]
    show("alice look", F("look", {"tag": tag}, a))
    show("bob look", F("look", {"tag": tag}, b))
    ad = show("alice make_deck", F("make_deck", {"tag": tag, "name": "alice-" + tag, "count": 4}, a))
    bd = show("bob make_deck", F("make_deck", {"tag": tag, "name": "bob-" + tag, "count": 2}, b))
    if "deck" not in ad or "deck" not in bd: return
    show("alice my_deck(own)", F("my_deck", {"deck_id": ad["deck"]}, a))
    show("bob my_deck(own)", F("my_deck", {"deck_id": bd["deck"]}, b))
    print("---- leak probes")
    show("alice probe(card)", F("probe", {"node_id": card}, a))
    show("bob probe(card)", F("probe", {"node_id": card}, b))
    show("carol probe(card) (no deck)", F("probe", {"node_id": card}, c))
    show("bob probe(catalog)", F("probe", {"node_id": cat}, b))
    show("bob resolve(alice deck, alice edge, alice root)", F("resolve", {"ids": [ad["deck"]] + ad["edges"] + [ar]}, b))
    show("bob my_deck(alice deck)", F("my_deck", {"deck_id": ad["deck"]}, b))
    show("bob walker ReadDeck on alice deck", call("/walker/ReadDeck/" + ad["deck"], {}, b))
    show("bob walker ReadDeck on own deck", call("/walker/ReadDeck/" + bd["deck"], {}, b))
    show("bob walker BackFromCard", call("/walker/BackFromCard/" + card, {}, b))
    show("bob walker BackEdgesFromCard", call("/walker/BackEdgesFromCard/" + card, {}, b))
    show("alice walker BackFromCard", call("/walker/BackFromCard/" + card, {}, a))
    show("anon walker BackFromCard", call("/walker/BackFromCard/" + card, {}))
    print("---- sharing")
    show("alice share deck with bob (deck only)", F("share", {"deck_id": ad["deck"], "target_root": br, "with_edges": False, "with_all": False}, a))
    show("bob my_deck(alice deck) after deck-only grant", F("my_deck", {"deck_id": ad["deck"]}, b))
    show("bob ReadDeck walker after deck-only grant", call("/walker/ReadDeck/" + ad["deck"], {}, b))
    show("carol my_deck(alice deck) after grant to bob", F("my_deck", {"deck_id": ad["deck"]}, c))
    show("bob probe(card) after deck-only grant", F("probe", {"node_id": card}, b))
    show("alice share deck with bob (deck + edges)", F("share", {"deck_id": ad["deck"], "target_root": br, "with_edges": True, "with_all": False}, a))
    show("bob my_deck(alice deck) after deck+edges grant", F("my_deck", {"deck_id": ad["deck"]}, b))
    show("bob probe(card) after deck+edges grant", F("probe", {"node_id": card}, b))
    show("carol probe(card) after grant to bob", F("probe", {"node_id": card}, c))
    show("bob rename alice deck with READ", F("rename_node", {"node_id": ad["deck"], "name": "HACKED"}, b))
    show("alice my_deck(own) after bob rename attempt", F("my_deck", {"deck_id": ad["deck"]}, a))
    show("alice unshare", F("unshare", {"deck_id": ad["deck"], "target_root": br}, a))
    show("bob my_deck(alice deck) after unshare", F("my_deck", {"deck_id": ad["deck"]}, b))
    show("bob probe(card) after unshare", F("probe", {"node_id": card}, b))
    print("---- writes to shared nodes")
    show("bob rename card", F("rename_node", {"node_id": card, "name": "HACKED-by-bob"}, b))
    show("bob rename format", F("rename_node", {"node_id": fmt, "name": "HACKED-by-bob"}, b))
    show("alice look after bob renames", F("look", {"tag": tag}, a))
    show("guest (anonymous :pub) rename card", F("rename_node_pub", {"node_id": card, "name": "refreshed-by-guest"}))
    show("alice look after guest rename", F("look", {"tag": tag}, a))
    show("alice rename card", F("rename_node", {"node_id": card, "name": "refreshed-by-alice"}, a))
    show("bob look after alice rename", F("look", {"tag": tag}, b))
    show("bob attach junk to card", F("attach_junk", {"node_id": card}, b))
    show("alice probe(card) after bob junk", F("probe", {"node_id": card}, a))
    show("bob delete_in_edges(card)", F("delete_in_edges", {"node_id": card}, b))
    show("alice my_deck(own) after bob deleted in-edges", F("my_deck", {"deck_id": ad["deck"]}, a))
    show("bob my_deck(own) after deleting in-edges", F("my_deck", {"deck_id": bd["deck"]}, b))
    show("bob delete format", F("delete_node", {"node_id": fmt}, b))
    show("bob delete card", F("delete_node", {"node_id": card}, b))
    show("alice look after bob deletes", F("look", {"tag": tag}, a))
    show("alice my_deck(own) after bob deletes", F("my_deck", {"deck_id": ad["deck"]}, a))

