"""Build mana_symbols.css: Magic's mana and tap symbols from the Mana font, cut down to
the symbols the catalogue uses.

The Mana font (Andrew Gioia, https://github.com/andrewgioia/mana) draws the game's
symbols as a font: the font is SIL OFL 1.1, its CSS MIT, and the symbol designs are
copyright Wizards of the Coast. This keeps only the CSS rules for the symbol classes in
SYMBOL_CLASSES and subsets the font to the glyphs those rules use, inlined as a data: URI,
so the web app and the chat views (which can't fetch fonts from inside the host) share
one small stylesheet.

    python scripts/mana_symbols.py <mana-font package dir>

The package dir is the unpacked npm tarball (registry.npmjs.org/mana-font/-/mana-font-<v>.tgz),
holding css/mana.css and fonts/mana.woff2. Needs fontTools and brotli, which are not
project dependencies: run it from any Python that has them (pip install fonttools brotli).
"""

import base64
import io
import json
import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "mana_symbols.css"

# Every symbol the catalogue's costs and rules text use (see manaClass in
# mana_cost.jac), plus the frame classes their rules need.
SYMBOL_CLASSES = {
    *"wubrgcxyzsedlhp",
    *(str(n) for n in range(0, 21)), "100", "1000000", "1-2", "infinity",
    "wu", "wb", "ub", "ur", "br", "bg", "rw", "rg", "gw", "gu",
    "2w", "2u", "2b", "2r", "2g", "cw", "cu", "cb", "cr", "cg",
    "wp", "up", "bp", "rp", "gp",
    "wup", "wbp", "ubp", "urp", "brp", "bgp", "rwp", "rgp", "gwp", "gup",
    "tap", "untap", "chaos", "acorn", "ticket",
}
FRAME_CLASSES = {"ms", "ms-cost", "ms-half"}
ALLOWED = FRAME_CLASSES | {"ms-" + s for s in SYMBOL_CLASSES}


def rules(css: str):
    """Top-level (selector, body) pairs; @-blocks are skipped."""
    i = 0
    while True:
        start = css.find("{", i)
        if start < 0:
            return
        selector = css[i:start].strip()
        depth, j = 1, start + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        body = css[start + 1 : j - 1].strip()
        selector = re.sub(r"/\*.*?\*/", "", selector, flags=re.S).strip()
        if not selector.startswith("@"):
            yield selector, body
        i = j


def kept(selector: str) -> str:
    """The parts of a selector list whose classes are all allowed, or ""."""
    parts = [p.strip() for p in selector.split(",")]
    ok = [p for p in parts if set(re.findall(r"\.([a-z0-9-]+)", p)) <= ALLOWED and ".ms" in p]
    return ", ".join(ok)


def main(package: Path) -> None:
    css = (package / "css" / "mana.css").read_text()
    version = json.loads((package / "package.json").read_text())["version"]
    out_rules = []
    for selector, body in rules(css):
        sel = kept(selector)
        if sel:
            out_rules.append(f"{sel} {{\n  {body}\n}}")
    text = "\n".join(out_rules)
    codepoints = {int(h, 16) for h in re.findall(r'content:\s*"\\([0-9a-f]{4})"', text)}

    font = TTFont(package / "fonts" / "mana.woff2")
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    sub = subset.Subsetter(options)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    # Mana's glyphs record a left side bearing of 0 although their outlines start further
    # in. Its own WOFF2 leaves the bearings out, so browsers take them from the outlines;
    # written back as 0 they would draw every glyph shifted left. Match them to the outlines.
    glyf, hmtx = font["glyf"], font["hmtx"]
    for name in font.getGlyphOrder():
        glyph = glyf[name]
        if glyph.numberOfContours:
            glyph.recalcBounds(glyf)
            hmtx[name] = (hmtx[name][0], glyph.xMin)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    data = base64.b64encode(buf.getvalue()).decode()

    OUT.write_text(
        f"/* Magic's mana and tap symbols, generated by scripts/mana_symbols.py from the Mana font {version}\n"
        "   (Andrew Gioia, https://github.com/andrewgioia/mana): the font is SIL OFL 1.1 (licenses/mana-font-OFL.txt, which also holds the CSS's MIT notice), its CSS is MIT,\n"
        "   and the symbol designs are copyright Wizards of the Coast. Do not edit by hand. */\n\n"
        "@font-face {\n"
        '  font-family: "Mana";\n'
        f'  src: url("data:font/woff2;base64,{data}") format("woff2");\n'
        "  font-weight: normal;\n  font-style: normal;\n}\n"
        + text
        + "\n"
    )
    print(f"{OUT.name}: {len(out_rules)} rules, {len(codepoints)} glyphs, font {len(buf.getvalue())} bytes")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
